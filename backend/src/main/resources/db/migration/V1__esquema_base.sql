-- MediCita: un consultorio y un solo medico.
-- Los identificadores se generan automaticamente.

CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(20) NOT NULL UNIQUE,
    CONSTRAINT roles_nombre_valido
        CHECK (nombre IN ('ADMIN', 'MEDICO', 'PACIENTE'))
);

CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    telefono VARCHAR(20) NOT NULL,
    avatar_url VARCHAR(500),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    rol_id BIGINT NOT NULL REFERENCES roles(id),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Impide registrar el mismo correo con distintas mayusculas.
CREATE UNIQUE INDEX usuarios_email_unico
    ON usuarios (LOWER(email));

CREATE INDEX usuarios_rol_idx ON usuarios (rol_id);

CREATE TABLE servicios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    descripcion VARCHAR(500),
    duracion_min INTEGER NOT NULL,
    precio NUMERIC(10,2) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT servicios_duracion_valida CHECK (duracion_min > 0),
    CONSTRAINT servicios_precio_valido CHECK (precio >= 0)
);

CREATE TABLE horarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dia_semana SMALLINT NOT NULL,
    hora_inicio TIME NOT NULL,
    hora_fin TIME NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    -- 1 = lunes; 7 = domingo. Cada intervalo termina el mismo dia.
    CONSTRAINT horarios_dia_valido CHECK (dia_semana BETWEEN 1 AND 7),
    CONSTRAINT horarios_intervalo_valido CHECK (hora_fin > hora_inicio),
    CONSTRAINT horarios_intervalo_unico
        UNIQUE (dia_semana, hora_inicio, hora_fin)
);

-- Relacion muchos a muchos: horarios <-> servicios.
CREATE TABLE horario_servicio (
    horario_id BIGINT NOT NULL REFERENCES horarios(id),
    servicio_id BIGINT NOT NULL REFERENCES servicios(id),
    PRIMARY KEY (horario_id, servicio_id)
);

CREATE INDEX horario_servicio_servicio_idx
    ON horario_servicio (servicio_id);

CREATE TABLE bloqueos_horario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inicio TIMESTAMPTZ NOT NULL,
    fin TIMESTAMPTZ NOT NULL,
    motivo VARCHAR(250) NOT NULL,
    CONSTRAINT bloqueos_intervalo_valido CHECK (fin > inicio)
);

CREATE TABLE citas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id BIGINT NOT NULL REFERENCES usuarios(id),
    servicio_id BIGINT NOT NULL REFERENCES servicios(id),
    inicio TIMESTAMPTZ NOT NULL,
    fin TIMESTAMPTZ NOT NULL,
    precio_reservado NUMERIC(10,2) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'confirmada',
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT citas_intervalo_valido CHECK (fin > inicio),
    CONSTRAINT citas_precio_valido CHECK (precio_reservado >= 0),
    CONSTRAINT citas_estado_valido CHECK (
        estado IN ('confirmada', 'completada', 'cancelada', 'no_asistio')
    )
);

-- Una sola agenda: dos citas confirmadas no pueden empalmarse.
-- [) incluye el inicio y excluye el fin:
-- 10:00-10:30 y 10:30-11:00 pueden coexistir.
ALTER TABLE citas
    ADD CONSTRAINT citas_sin_traslape
    EXCLUDE USING gist (
        tstzrange(inicio, fin, '[)') WITH &&
    )
    WHERE (estado = 'confirmada');

CREATE INDEX citas_paciente_inicio_idx ON citas (paciente_id, inicio);
CREATE INDEX citas_servicio_idx ON citas (servicio_id);
CREATE INDEX citas_inicio_idx ON citas (inicio);

CREATE TABLE historial_estados (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cita_id BIGINT NOT NULL REFERENCES citas(id),
    estado_anterior VARCHAR(20),
    estado_nuevo VARCHAR(20) NOT NULL,
    cambiado_por BIGINT NOT NULL REFERENCES usuarios(id),
    fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT historial_anterior_valido CHECK (
        estado_anterior IS NULL OR estado_anterior IN (
            'confirmada', 'completada', 'cancelada', 'no_asistio'
        )
    ),
    CONSTRAINT historial_nuevo_valido CHECK (
        estado_nuevo IN (
            'confirmada', 'completada', 'cancelada', 'no_asistio'
        )
    )
);

CREATE INDEX historial_cita_idx ON historial_estados (cita_id);
CREATE INDEX historial_usuario_idx ON historial_estados (cambiado_por);

-- Solo permite una fila: la configuracion del consultorio.
CREATE TABLE configuracion_consultorio (
    id BIGINT PRIMARY KEY DEFAULT 1,
    nombre VARCHAR(150) NOT NULL,
    telefono VARCHAR(20) NOT NULL,
    direccion VARCHAR(300) NOT NULL,
    zona_horaria VARCHAR(60) NOT NULL DEFAULT 'America/Mexico_City',
    CONSTRAINT configuracion_fila_unica CHECK (id = 1)
);

CREATE TABLE password_reset_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    expira_en TIMESTAMPTZ NOT NULL,
    usado BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX password_reset_usuario_idx
    ON password_reset_tokens (usuario_id);

CREATE TABLE tokens_revocados (
    jti VARCHAR(100) PRIMARY KEY,
    expira_en TIMESTAMPTZ NOT NULL
);

CREATE INDEX tokens_revocados_expiracion_idx
    ON tokens_revocados (expira_en);